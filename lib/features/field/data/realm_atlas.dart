import 'design_persona.dart';

/// The type of a Realm — a Dart port of `realm-atlas.ts` `AtlasRealmType`.
enum AtlasRealmType {
  ecosystem,
  organization,
  alliance,
  program,
  project,
  dyad,
  community,
  institution,
  council,
  concept,
  cell,
  clan;

  /// Human-readable label (e.g. `Organization`) used for the type eyebrow.
  String get label {
    switch (this) {
      case AtlasRealmType.ecosystem:
        return 'Ecosystem';
      case AtlasRealmType.organization:
        return 'Organization';
      case AtlasRealmType.alliance:
        return 'Alliance';
      case AtlasRealmType.program:
        return 'Program';
      case AtlasRealmType.project:
        return 'Project';
      case AtlasRealmType.dyad:
        return 'Dyad';
      case AtlasRealmType.community:
        return 'Community';
      case AtlasRealmType.institution:
        return 'Institution';
      case AtlasRealmType.council:
        return 'Council';
      case AtlasRealmType.concept:
        return 'Concept';
      case AtlasRealmType.cell:
        return 'Cell';
      case AtlasRealmType.clan:
        return 'Clan';
    }
  }

  /// The realm-emblem asset key for this type. Types without a dedicated emblem
  /// fall back to the generic `conceptual` emblem.
  String get emblemKey {
    switch (this) {
      case AtlasRealmType.organization:
        return 'organization';
      case AtlasRealmType.alliance:
        return 'alliance';
      case AtlasRealmType.community:
        return 'community';
      case AtlasRealmType.program:
        return 'program';
      case AtlasRealmType.project:
        return 'project';
      case AtlasRealmType.ecosystem:
      case AtlasRealmType.institution:
      case AtlasRealmType.dyad:
      case AtlasRealmType.council:
      case AtlasRealmType.concept:
      case AtlasRealmType.cell:
      case AtlasRealmType.clan:
        return 'conceptual';
    }
  }
}

/// A single Realm in the atlas.
class AtlasRealm {
  const AtlasRealm({
    required this.id,
    required this.name,
    required this.type,
    required this.parent,
    required this.purpose,
    required this.motif,
    this.children = const [],
    this.visibleTo,
    this.fixture = false,
  });

  final String id;
  final String name;
  final AtlasRealmType type;
  final String? parent;
  final String purpose;

  /// A glyph that stands in for the Realm before a Portrait/emblem loads.
  final String motif;
  final List<String> children;

  /// Personas (other than Alice) this Realm is visible to. `null` means the
  /// Realm is only in Alice's Ecosystem-wide view.
  final List<DesignPersona>? visibleTo;

  /// `true` for proposed legal Institutions (held back until verified).
  final bool fixture;
}

