/// The Realms visible to [persona] as children of [realmId].
///
/// Alice sees everything; other personas see only Realms whose `visibleTo`
/// names them. Visibility is a per-persona overlay — it never mutates the graph.
List<AtlasRealm> visibleChildren(String realmId, DesignPersona persona) {
  final current = realmAtlas[realmId];
  if (current == null) {
    return const [];
  }
  final ids = realmId == 'kinship-duna'
      ? personaTopLevel[persona]!
      : current.children;
  return ids
      .map((id) => realmAtlas[id])
      .whereType<AtlasRealm>()
      .where(
        (realm) =>
            persona == DesignPersona.alice ||
            (realm.visibleTo?.contains(persona) ?? false),
      )
      .toList();
}

